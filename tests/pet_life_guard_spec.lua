package.path='./?.lua;'..package.path
local guard=require('petLifeGuard')
local g=guard.new({zero_grace=.35,missing_grace=.4})
assert(not g:missing(1))
g:track(4001)
assert(g:health(0,1)=='uninitialized',
    'initial 0% HP is not a live summon or death')
assert(not g.alive)
assert(g:health(99,1.1)=='alive')
assert(g.alive and g.zero_since==nil)
assert(g:health(0,1.2)=='zero_pending')
assert(g:health(0,1.4)=='zero_pending')
assert(g:health(100,1.45)=='alive','recovered HP must cancel false death')
assert(g.zero_since==nil)
assert(g:health(0,1.5)=='zero_pending')
assert(g:health(0,1.85)=='dead','persistent zero confirms death')
g:clear()
g:track(4001)
assert(g:health(0,2)=='uninitialized')
assert(g:health(98,2.05)=='alive','same summon ID can be reused')
assert(not g:missing(2.10))
assert(not g:missing(2.30))
g:present()
assert(not g:missing(2.4),'one dropped entity lookup must not depart')
assert(not g:missing(2.7))
assert(g:missing(3.0),'stable absence must depart')
g:clear()
assert(not g:missing(4))
g:track(4002)
assert(g:health(nil,4)=='unknown')
assert(g:health(-1,4)=='unknown')
assert(g:health(101,4)=='unknown')
assert(g:health(0/0,4)=='unknown')
assert(g:health(0,4)=='uninitialized')
assert(g:health(80,4.1)=='alive')
g:track(4003)
assert(not g.alive and not g.zero_since and not g.missing_since)
assert(g:health(0,4.2)=='uninitialized',
    'a replacement pet must never inherit last pet death state')
print('PetBar summon vitality/visibility guard: PASS')
